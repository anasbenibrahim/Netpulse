-- NetPulse initial schema.
-- Kept to portable SQL so the same migration runs on PostgreSQL (prod) and H2 (tests).

CREATE TABLE devices (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code  VARCHAR(64)              NOT NULL,
    name         VARCHAR(128)             NOT NULL,
    ip_address   VARCHAR(45),
    ssid         VARCHAR(64),
    status       VARCHAR(16)              NOT NULL,
    last_seen    TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_devices_device_code UNIQUE (device_code)
);

-- System telemetry: netpulse/devices/{code}/telemetry
CREATE TABLE telemetry (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id      BIGINT                   NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    uptime_seconds BIGINT,
    free_heap      BIGINT,
    total_heap     BIGINT,
    heap_usage     DOUBLE PRECISION,
    flash_size_mb  INTEGER,
    ssid           VARCHAR(64),
    ip_address     VARCHAR(45),
    rssi           DOUBLE PRECISION,
    received_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_telemetry_device_time ON telemetry (device_id, received_at);
CREATE INDEX idx_telemetry_time ON telemetry (received_at);

-- Network quality: netpulse/devices/{code}/network
-- Latency / packet-loss columns are NULL when the firmware could not measure them.
CREATE TABLE network_metrics (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id            BIGINT                   NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    rssi                 DOUBLE PRECISION,
    gateway_latency      DOUBLE PRECISION,
    gateway_packet_loss  DOUBLE PRECISION,
    internet_latency     DOUBLE PRECISION,
    internet_packet_loss DOUBLE PRECISION,
    health_score         DOUBLE PRECISION,
    network_status       VARCHAR(16),
    received_at          TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_network_device_time ON network_metrics (device_id, received_at);
CREATE INDEX idx_network_time ON network_metrics (received_at);

-- One row per anomaly episode: opened when a metric crosses a threshold,
-- updated while it stays abnormal, resolved when it is back to normal.
CREATE TABLE anomalies (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id         BIGINT                   NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    type              VARCHAR(40)              NOT NULL,
    metric_name       VARCHAR(40)              NOT NULL,
    severity          VARCHAR(16)              NOT NULL,
    status            VARCHAR(16)              NOT NULL,
    detected_value    DOUBLE PRECISION,
    threshold_value   DOUBLE PRECISION,
    description       VARCHAR(512)             NOT NULL,
    occurrences       INTEGER                  NOT NULL,
    normal_streak     INTEGER                  NOT NULL,
    first_detected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_detected_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at       TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_anomalies_device_type_status ON anomalies (device_id, type, status);
CREATE INDEX idx_anomalies_status_time ON anomalies (status, last_detected_at);

CREATE TABLE alerts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id       BIGINT                   NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    anomaly_id      BIGINT                   NOT NULL REFERENCES anomalies (id) ON DELETE CASCADE,
    title           VARCHAR(160)             NOT NULL,
    message         VARCHAR(512)             NOT NULL,
    severity        VARCHAR(16)              NOT NULL,
    status          VARCHAR(16)              NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    acknowledged_at TIMESTAMP WITH TIME ZONE,
    resolved_at     TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_alerts_status_time ON alerts (status, created_at);
CREATE INDEX idx_alerts_anomaly ON alerts (anomaly_id);
